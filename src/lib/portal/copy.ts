/** What each journal event says to the client. */
export function eventText(lang: Lang, type: string, data: Record<string, unknown>, stageLabel: (s: string) => string): string | null {
  const n = data.number;
  const F: Record<string, string> = {
    "project.created": "Projet ouvert.",
    "project.stage": `Étape suivante : ${stageLabel(String(data.stage))}.`,
    "version.shared": `Version ${n} partagée.`,
    "version.approved": `Version ${n} approuvée.`,
    "version.changes_requested": `Vos commentaires sur la version ${n}.`,
    "invoice.sent": `Facture ${n} envoyée.`,
    "invoice.paid": `Facture ${n} payée.`,
    "invoice.void": `Facture ${n} annulée.`,
    "care.active": "Entretien activé.",
    "care.past_due": "Le paiement de l'entretien n'est pas passé.",
    "care.canceled": "Entretien arrêté.",
  };
  const E: Record<string, string> = {
    "project.created": "Project opened.",
    "project.stage": `Next stage: ${stageLabel(String(data.stage))}.`,
    "version.shared": `Version ${n} shared.`,
    "version.approved": `Version ${n} approved.`,
    "version.changes_requested": `Your feedback on version ${n}.`,
    "invoice.sent": `Invoice ${n} sent.`,
    "invoice.paid": `Invoice ${n} paid.`,
    "invoice.void": `Invoice ${n} canceled.`,
    "care.active": "Care plan started.",
    "care.past_due": "The care plan payment didn't go through.",
    "care.canceled": "Care plan stopped.",
  };
  return (lang === "fr" ? F : E)[type] ?? null;
}
